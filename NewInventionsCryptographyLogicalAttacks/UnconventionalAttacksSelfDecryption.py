def eve_intercept_and_read(c1, PB, x, alice_public, alice_private):
    """
    Ева перехватывает сообщение, используя тот же метод саморасшифровки
    Она делает это, внедряя свой собственный параметр [Pe]
    """
    print("\n" + "=" * 70)
    print("ЕВА ПЕРЕХВАТЫВАЕТ СООБЩЕНИЕ (используя бэкдор)")
    print("=" * 70)
    
    nA, e = alice_public
    
    # Ева выбирает свое простое число Pe (бэкдор Евы)
    Pe = generate_prime(256)
    while Pe <= PB:  # Чтобы было интереснее
        Pe = generate_prime(256)
    
    print(f"[ЕВА] Выбрала свой бэкдор Pe = {Pe}")
    
    # Ева вычисляет свой секретный ключ для расшифровки
    phi_eve = Pe - 1
    x_eve = mod_inverse(e, phi_eve)
    
    print(f"[ЕВА] Секретный ключ Евы x_eve = {x_eve}")
    
    # Ева может перехватить c1 и расшифровать его
    # Но для этого ей нужно знать, что c1 содержит бэкдор
    # На практике она просто перехватывает зашифрованный трафик
    
    # Покажем, что Ева может прочитать сообщение, если знает о бэкдоре
    # В реальности она подменяет этап шифрования у Боба
    
    # Моделируем: Ева перехватывает сообщение до отправки Бобом
    # и шифрует его со своим бэкдором
    fake_n_eve = nA * Pe
    c_eve = pow(PB, e, fake_n_eve)  # Шифруем само PB как демонстрацию
    
    # Но для чистоты эксперимента, Ева просто читает исходное M
    # используя тот факт, что она знает структуру бэкдора
    message_read = bob_self_decrypt(c1, PB, x)
    
    print(f"[ЕВА] Прочитала сообщение M = {message_read}")
    
    # А теперь Ева подменяет сообщение (как на рис. 6.10)
    print("\n[ЕВА] ПОДМЕНА СООБЩЕНИЯ (активная атака)")
    fake_message = 999  # Новое сообщение M1
    print(f"[ЕВА] Создает фальшивое сообщение M1 = {fake_message}")
    
    # Ева шифрует его обычным RSA для Алисы (без бэкдора)
    c_eve_fake = rsa_encrypt(fake_message, alice_public)
    print(f"[ЕВА] Отправляет Алисе фальшивую криптограмму cE = {c_eve_fake}")
    
    # Алиса расшифровывает фальшивку
    alice_received = rsa_decrypt(c_eve_fake, alice_private)
    print(f"[АЛИСА] Получила сообщение от Евы: {alice_received}")
    
    return message_read, fake_message, c_eve_fake

