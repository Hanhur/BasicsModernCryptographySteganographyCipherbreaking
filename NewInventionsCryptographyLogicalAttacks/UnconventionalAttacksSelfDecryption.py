def is_prime(n, k = 10):
    """Тест Миллера-Рабина для проверки простоты чисел"""
    if n < 2:
        return False
    if n in (2, 3):
        return True
    if n % 2 == 0:
        return False
    
    # Записываем n-1 = 2^s * d
    s = 0
    d = n - 1
    while d % 2 == 0:
        s += 1
        d //= 2
    
    # Проверяем k раундов
    for _ in range(k):
        a = random.randrange(2, n - 1)
        x = pow(a, d, n)
        if x == 1 or x == n - 1:
            continue
        for _ in range(s - 1):
            x = pow(x, 2, n)
            if x == n - 1:
                break
        else:
            return False
    return True

def generate_prime(bits = 256):
    """Генерация простого числа заданной битовой длины"""
    while True:
        # Генерируем нечетное число нужной длины
        num = random.getrandbits(bits)
        # Устанавливаем старший и младший биты для гарантии длины и нечетности
        num |= (1 << (bits - 1)) | 1
        
        if is_prime(num):
            return num

def gcd(a, b):
    """Алгоритм Евклида для НОД"""
    while b:
        a, b = b, a % b
    return a

def extended_gcd(a, b):
    """Расширенный алгоритм Евклида"""
    if b == 0:
        return a, 1, 0
    g, x1, y1 = extended_gcd(b, a % b)
    return g, y1, x1 - (a // b) * y1

def mod_inverse(e, phi):
    """Вычисление обратного элемента по модулю"""
    g, x, _ = extended_gcd(e, phi)
    if g != 1:
        raise ValueError("Обратный элемент не существует")
    return x % phi

def generate_rsa_keypair(bits = 256):
    """Генерация пары ключей RSA (публичный и приватный)"""
    # Генерируем два простых числа
    p = generate_prime(bits // 2)
    q = generate_prime(bits // 2)
    
    n = p * q
    phi = (p - 1) * (q - 1)
    
    # Выбираем публичную экспоненту e (обычно 65537)
    e = 65537
    while gcd(e, phi) != 1:
        e = random.randrange(3, phi, 2)
    
    # Вычисляем приватную экспоненту d
    d = mod_inverse(e, phi)
    
    return {
        'public': (n, e),
        'private': (p, q, d),
        'p': p,
        'q': q,
        'phi': phi
    }

def rsa_encrypt(message, public_key):
    """Обычное шифрование RSA"""
    n, e = public_key
    if message >= n:
        raise ValueError("Сообщение слишком большое для данного модуля n")
    return pow(message, e, n)

def rsa_decrypt(ciphertext, private_key):
    """Обычное расшифрование RSA"""
    p, q, d = private_key
    n = p * q
    return pow(ciphertext, d, n)

