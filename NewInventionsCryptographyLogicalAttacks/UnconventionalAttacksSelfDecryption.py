def kleptographic_encrypt_with_backdoor(message, alice_public, bob_private):
    """
    Боб шифрует сообщение с ВНЕДРЕННЫМ БЭКДОРОМ [PB]
    
    Параметры:
    - message: секретное сообщение [M]
    - alice_public: открытый ключ Алисы (NA, e)
    - bob_private: закрытый ключ Боба (pB, qB, dB) - нужен для получения PB
    
    Возвращает:
    - c1: фальшивая криптограмма (с бэкдором)
    - PB: бэкдор-параметр (простое число)
    - x: секретный ключ Боба для саморасшифровки
    """
    nA, e = alice_public
    
    # ШАГ 1: Боб выбирает простое число [PB] > [M]
    # Это и есть БЭКДОР
    PB = generate_prime(256)
    while PB <= message:
        PB = generate_prime(256)
    
    print(f"\n[БЭКДОР] Боб выбрал простое число PB = {PB}")
    
    # ШАГ 2: Модифицированное шифрование
    # c1 ≡ M^e (mod NA * PB)
    fake_n = nA * PB
    c1 = pow(message, e, fake_n)
    
    print(f"[БЭКДОР] Фальшивая криптограмма c1 = {c1}")
    print(f"[БЭКДОР] Размер c1: {c1.bit_length()} бит (обычный размер: {nA.bit_length()} бит)")
    
    # ШАГ 3: Боб вычисляет секретный параметр [x]
    # e * x ≡ 1 (mod PB - 1)
    phi_backdoor = PB - 1
    x = mod_inverse(e, phi_backdoor)
    
    print(f"[БЭКДОР] Секретный ключ Боба x = {x}")
    
    return c1, PB, x

def bob_self_decrypt(c1, PB, x):
    """
    САМОРАСШИФРОВКА БОБА (магическая функция)
    Боб может расшифровать криптограмму, используя свой секретный ключ x
    """
    # (c1)^x ≡ M (mod PB)
    message_recovered = pow(c1, x, PB)
    return message_recovered

def alice_decrypt(c1, alice_private):
    """
    Алиса расшифровывает фальшивую криптограмму обычным способом
    Она даже не подозревает о существовании бэкдора!
    """
    p, q, d = alice_private
    n = p * q
    
    # Обычное расшифрование: (c1)^dA ≡ M (mod NA)
    # Но почему это работает?
    # Потому что c1 = M^e (mod NA * PB), значит c1 = M^e + k*(NA*PB)
    # При возведении в степень dA по модулю NA, член k*(NA*PB) обнуляется
    # Остается M^(e*dA) ≡ M (mod NA)
    message_recovered = pow(c1, d, n)
    return message_recovered

