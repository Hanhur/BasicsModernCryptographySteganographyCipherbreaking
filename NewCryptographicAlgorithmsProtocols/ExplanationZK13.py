def demo_protocol():
    """Полная демонстрация работы протокола ZK13."""
    print("=" * 60)
    print("ПРОТОКОЛ ZK13 - ДЕМОНСТРАЦИЯ")
    print("=" * 60)
    
    # 1. Генерация открытых параметров
    print("\n[1] Генерация открытых параметров...")
    p, g = generate_parameters(bits = 12)
    print(f"    Открытые параметры: p = {p}, g = {g}")
    
    # 2. Общий секрет (известен обеим сторонам)
    print("\n[2] Общий секрет...")
    secret = 42  # Это может быть любое число
    print(f"    Секрет s = {secret}")
    
    # 3. Вычисление хеша от секрета (делают обе стороны независимо)
    print("\n[3] Вычисление хеша от секрета...")
    secret_hash = compute_hash(secret, p)
    print(f"    H[s] = {secret_hash}")
    
    # 4. Боб (Prover) генерирует доказательство
    print("\n[4] Боб генерирует доказательство (Шаг 1)...")
    r, P, k = step_1_prover(p, g, secret_hash)
    print(f"    Боб отправляет Алисе пару: (P = {P}, r = {r})")
    
    # 5. Алиса (Verifier) проверяет доказательство
    print("\n[5] Алиса проверяет доказательство (Шаг 2)...")
    result = step_2_verifier(p, g, secret_hash, r, P)
    
    # 6. Итог
    print("\n" + "=" * 60)
    if result:
        print("✅ АУТЕНТИФИКАЦИЯ УСПЕШНА: Боб доказал знание секрета!")
    else:
        print("❌ АУТЕНТИФИКАЦИЯ ПРОВАЛЕНА: Боб НЕ знает секрет!")
    print("=" * 60)
    
    return result

def demo_attack():
    """
    Демонстрация попытки атаки: злоумышленник пытается подделать доказательство,
    не зная секрета.
    """
    print("\n" + "=" * 60)
    print("ДЕМОНСТРАЦИЯ АТАКИ (злоумышленник не знает секрет)")
    print("=" * 60)
    
    # Открытые параметры
    p, g = generate_parameters(bits = 12)
    
    # Секрет известен только Алисе
    real_secret = 42
    real_hash = compute_hash(real_secret, p)
    print(f"    Реальный H[s] = {real_hash}")
    
    # Злоумышленник использует неверный хеш
    fake_secret = 999
    fake_hash = compute_hash(fake_secret, p)
    print(f"    Поддельный H[s'] = {fake_hash}")
    
    # Злоумышленник генерирует доказательство с поддельным хешем
    print("\n[Атакующий] Генерирует поддельное доказательство...")
    k_attack = random.randint(2, p - 2)
    r_attack = pow(g, k_attack, p)
    F_attack = (fake_hash * k_attack) % (p - 1)
    P_attack = pow(g, F_attack, p)
    print(f"    Атакующий отправляет: (P = {P_attack}, r = {r_attack})")
    
    # Алиса проверяет со своим реальным хешем
    print("\n[Алиса] Проверка с реальным H[s]...")
    result = step_2_verifier(p, g, real_hash, r_attack, P_attack)
    
    print("\n" + "=" * 60)
    if not result:
        print("✅ Атака ОТРАЖЕНА: поддельное доказательство не прошло проверку!")
    else:
        print("⚠️ Атака УСПЕШНА: протокол скомпрометирован (этого не должно быть)!")
    print("=" * 60)
    
    return result

