def generate_parameters(bits: int = 12) -> tuple:
    """
    Генерирует открытые параметры: простое число p и образующий элемент g.
    bits - количество бит для p (по умолчанию 12 для быстрых вычислений).
    Для демонстрации используется простой перебор.
    """
    # Для демонстрации берём небольшое простое число
    # В реальных протоколах p должно быть 1024+ бит
    small_primes = [2741, 3257, 3673, 4099, 4457, 4931, 5237, 5741, 6029, 6653]
    
    for p in small_primes:
        if p >= (1 << (bits - 1)):
            g = find_primitive_root(p)
            if g != -1:
                print(f"[Параметры] p = {p}, g = {g}")
                return p, g
    
    # Если не нашли в списке - генерируем случайное простое (для малых чисел)
    while True:
        p = random.randint(2 ** (bits - 1), 2 ** bits)
        if is_prime(p):
            g = find_primitive_root(p)
            if g != -1:
                print(f"[Параметры] p = {p}, g = {g}")
                return p, g

def compute_hash(secret: int, p: int) -> int:
    """
    Вычисляет хеш от секрета.
    Используется SHA-256, результат приводится к модулю (p-1).
    """
    secret_bytes = str(secret).encode('utf-8')
    hash_bytes = hashlib.sha256(secret_bytes).digest()
    # Преобразуем хеш в число и берём по модулю (p-1)
    hash_int = int.from_bytes(hash_bytes, byteorder = 'big')
    return hash_int % (p - 1)

def step_1_prover(p: int, g: int, secret_hash: int) -> tuple:
    """
    Шаг 1а и 1б: Боб (доказывающий) генерирует доказательство.
    
    Возвращает:
        r - случайный элемент r = g ^ k mod p
        P - доказательство P = g ^ F mod p, где F = H[s] * k mod (p-1)
        k - случайное число (для внутреннего использования, не отправляется)
    """
    # Шаг 1а: Боб выбирает случайное k (1 < k < p-1)
    k = random.randint(2, p - 2)
    print(f"[Боб] Случайное число k = {k}")
    
    # r = g^k mod p
    r = pow(g, k, p)
    print(f"[Боб] r = {g}^{k} mod {p} = {r}")
    
    # Шаг 1б: вычисляем F = H[s] * k mod (p-1)
    F = (secret_hash * k) % (p - 1)
    print(f"[Боб] F = {secret_hash} * {k} mod {p - 1} = {F}")
    
    # P = g^F mod p
    P = pow(g, F, p)
    print(f"[Боб] P = {g} ^ {F} mod {p} = {P}")
    
    return r, P, k

def step_2_verifier(p: int, g: int, secret_hash: int, r: int, P: int) -> bool:
    """
    Шаг 2: Алиса (проверяющий) проверяет доказательство.
    
    Возвращает:
        True - если доказательство верно, Боб знает секрет
        False - если доказательство неверно
    """
    print(f"\n[Алиса] Проверка доказательства...")
    print(f"[Алиса] Получено: r = {r}, P = {P}")
    print(f"[Алиса] Известный хеш секрета: H[s] = {secret_hash}")
    
    # V = r^H[s] mod p
    V = pow(r, secret_hash, p)
    print(f"[Алиса] V = {r}^{secret_hash} mod {p} = {V}")
    
    # Сравниваем V и P
    if V == P:
        print("[Алиса] ✅ V == P - доказательство ПРИНЯТО!")
        return True
    else:
        print("[Алиса] ❌ V != P - доказательство ОТВЕРГНУТО!")
        return False

