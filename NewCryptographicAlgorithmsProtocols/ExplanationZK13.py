# Объяснение ZK13
"""
Реализация протокола ZK13
Протокол аутентификации с общим секретом на основе дискретного логарифмирования.
Не использует numpy, только стандартные средства Python.
"""

import hashlib
import random
import sys

# ============================================================================
# ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
# ============================================================================

def is_prime(n: int) -> bool:
    """Проверка числа на простоту (для малых чисел)."""
    if n < 2:
        return False
    if n % 2 == 0:
        return n == 2
    i = 3
    while i * i <= n:
        if n % i == 0:
            return False
        i += 2
    return True

def find_primitive_root(p: int) -> int:
    """
    Находит образующий элемент (примитивный корень) по модулю p.
    Работает корректно для простых чисел (p-1 факторизуется для демонстрации).
    Для реальных p используется более сложный алгоритм.
    """
    if p == 2:
        return 1
    
    # Факторизация p-1 для малых чисел (упрощённо)
    phi = p - 1
    factors = []
    n = phi
    d = 2
    while d * d <= n:
        if n % d == 0:
            factors.append(d)
            while n % d == 0:
                n //= d
        d += 1 if d == 2 else 2
    if n > 1:
        factors.append(n)
    
    # Поиск примитивного корня
    for g in range(2, p):
        ok = True
        for q in factors:
            if pow(g, phi // q, p) == 1:
                ok = False
                break
        if ok:
            return g
    return -1

def modinv(a: int, m: int) -> int:
    """Обратное число по модулю m (расширенный алгоритм Евклида)."""
    if m == 1:
        return 0
    a = a % m
    x0, x1 = 1, 0
    b = m
    while b:
        q = a // b
        a, b = b, a - q * b
        x0, x1 = x1, x0 - q * x1
    return x0 % m

