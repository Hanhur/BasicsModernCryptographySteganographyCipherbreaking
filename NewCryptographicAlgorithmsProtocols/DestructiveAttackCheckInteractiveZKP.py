# 6. ДЕМОНСТРАЦИЯ: ПОЧЕМУ ЕСЛИ ЕВА ЗНАЕТ a, ТО АТАКА РАБОТАЕТ
# ------------------------------------------------------------

def run_eve_with_secret():
    """
    Демонстрация того, что если бы Ева знала a (но по условию не знает),
    то атака бы сработала. Это показывает, почему протокол защищён.
    """
    print("=" * 60)
    print("ДЕМОНСТРАЦИЯ: Если бы Ева знала a (чего быть не может)")
    print("=" * 60)
    
    # Шаг 1: как обычно
    k = random.randint(1, p - 2)
    V = mod_pow(g, k, p)
    print(f"Шаг 1: Пегги: k = {k}, V = {V}")
    
    k1 = random.randint(1, p - 2)
    V1 = mod_pow(g, k1, p)
    print(f"        Ева подменяет на V1 = {V1} (k1 = {k1})")
    
    # Шаг 2
    r = random.randint(1, p - 2)
    print(f"Шаг 2: Виктор отправляет r = {r}")
    
    # Шаг 3: Ева вычисляет w1, используя a (НО ЭТОГО НЕ МОЖЕТ СДЕЛАТЬ В РЕАЛЬНОСТИ!)
    # Предположим, Ева каким-то образом узнала a (например, перехватила)
    w1 = (k1 - a * r) % (p - 1)
    print(f"Шаг 3: Если бы Ева знала a = {a}, она бы вычислила:")
    print(f"        w1 = k1 - a * r mod (p - 1) = {w1}")
    
    # Проверка
    left = V1
    right = (mod_pow(g, w1, p) * mod_pow(B, r, p)) % p
    
    print(f"\nПРОВЕРКА:")
    print(f"  V1 = {left}")
    print(f"  g ^ w1 * B ^ r mod p = {right}")
    
    if left == right:
        print("  ✅ Проверка ПРОШЛА! (но только потому, что Ева знала a)")
        print("  В реальности Ева не знает a, поэтому атака невозможна.")
    print()

