# Проверка разрушительной атаки на интерактивный ZKP
"""
Моделирование интерактивного протокола Шнорра и атаки "человек посередине"
Без использования numpy
"""

import random
import math

# ------------------------------------------------------------
# 1. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ ДЛЯ РАБОТЫ С МОДУЛЯРНОЙ АРИФМЕТИКОЙ
# ------------------------------------------------------------

def mod_pow(base, exp, mod):
    """Быстрое возведение в степень по модулю (base ^ exp % mod)"""
    result = 1
    base = base % mod
    while exp > 0:
        if exp % 2 == 1:
            result = (result * base) % mod
        exp = exp >> 1
        base = (base * base) % mod
    return result

def mod_inverse(a, mod):
    """Находит обратное число по модулю (расширенный алгоритм Евклида)"""
    # Для простого модуля p можно использовать малую теорему Ферма: a^(p-2) % p
    # Но реализуем общий случай через расширенный алгоритм Евклида
    def egcd(a, b):
        if a == 0:
            return (b, 0, 1)
        else:
            g, y, x = egcd(b % a, a)
            return (g, x - (b // a) * y, y)
    
    g, x, _ = egcd(a, mod)
    if g != 1:
        raise ValueError("Обратного элемента не существует")
    else:
        return x % mod

def is_primitive_root(g, p):
    """Проверяет, является ли g первообразным корнем по модулю p"""
    if g == 0 or g == 1:
        return False
    
    # Факторизуем p-1
    factors = []
    n = p - 1
    d = 2
    while d * d <= n:
        if n % d == 0:
            factors.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        factors.append(n)
    
    # Проверяем условие: g^((p-1)/q) != 1 для всех простых q | (p-1)
    for q in factors:
        if mod_pow(g, (p - 1) // q, p) == 1:
            return False
    return True

def find_primitive_root(p):
    """Находит первообразный корень по модулю p"""
    # Просто перебираем, начиная с 2
    for g in range(2, p):
        if is_primitive_root(g, p):
            return g
    return None

