# 5. АТАКА ЕВЫ (ПОПЫТКА ПРОВЕСТИ MitM)
# ------------------------------------------------------------

def run_eve_attack():
    """
    Попытка атаки "человек посередине":
    Ева перехватывает V, заменяет на V1, но не знает a
    """
    print("=" * 60)
    print("ПОПЫТКА АТАКИ (Ева перехватывает и подменяет V)")
    print("=" * 60)
    
    # Шаг 1: Пегги выбирает k и отправляет V
    k = random.randint(1, p - 2)
    V = mod_pow(g, k, p)
    print(f"Шаг 1: Пегги выбрала k = {k}, вычислила V = g ^ k mod p = {V}")
    
    # Ева перехватывает V и подменяет на своё V1
    k1 = random.randint(1, p - 2)  # Ева придумывает своё случайное число
    V1 = mod_pow(g, k1, p)
    print(f"        🕵️ Ева перехватила V и заменила на V1 = g ^ k1 mod p = {V1}")
    print(f"        (Ева придумала k1 = {k1})")
    print(f"        Пегги отправляет V1 Виктору (думая, что это V)")
    
    # Шаг 2: Виктор получает V1 и отправляет r
    r = random.randint(1, p - 2)
    print(f"Шаг 2: Виктор получил V1, выбрал r = {r}")
    print(f"        Виктор отправляет r Пегги")
    
    # Ева перехватывает r (но не может его изменить, потому что Виктор уже его отправил)
    print(f"        🕵️ Ева перехватила r = {r}")
    
    # Шаг 3: Ева пытается вычислить w1 так, чтобы V1 == g^w1 * B^r mod p
    # Ей нужно решить уравнение: w1 = k1 - a*r mod (p-1)
    # Но Ева НЕ ЗНАЕТ a!
    print(f"Шаг 3: Ева пытается вычислить w1...")
    print(f"        Для проверки нужно: V1 == g ^ w1 * B ^ r mod p")
    print(f"        w1 = k1 - a * r mod (p - 1)")
    print(f"        ❌ Ева НЕ ЗНАЕТ a, поэтому не может вычислить w1!")
    
    # Ева пытается угадать w1 (берёт случайное значение)
    w1_guess = random.randint(0, p - 2)
    print(f"        Ева наугад подбирает w1 = {w1_guess}")
    
    # Проверка Виктора с поддельным w1
    left = V1
    right = (mod_pow(g, w1_guess, p) * mod_pow(B, r, p)) % p
    
    print(f"\nПРОВЕРКА ВИКТОРА (с поддельными V1 и w1):")
    print(f"  V1 = {left}")
    print(f"  g ^ w1 * B ^ r mod p = {right}")
    
    if left == right:
        print("  ✅ Атака УСПЕШНА! (вероятность 1 / (p - 1))")
    else:
        print("  ❌ Атака ПРОВАЛИЛАСЬ! Проверка не прошла.")
    print()

