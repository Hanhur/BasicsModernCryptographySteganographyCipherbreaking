# 4. ФУНКЦИЯ КОРРЕКТНОЙ РАБОТЫ ПРОТОКОЛА (БЕЗ АТАКИ)
# ------------------------------------------------------------

def run_honest_protocol():
    """Честное выполнение протокола Шнорра"""
    print("=" * 60)
    print("ЧЕСТНЫЙ ПРОТОКОЛ (Пегги доказывает Виктору знание a)")
    print("=" * 60)
    
    # Шаг 1: Пегги выбирает случайное k
    k = random.randint(1, p - 2)
    V = mod_pow(g, k, p)
    print(f"Шаг 1: Пегги выбрала k = {k}, вычислила V = g ^ k mod p = {V}")
    print(f"        Пегги отправляет V Виктору")
    
    # Шаг 2: Виктор выбирает случайный r
    r = random.randint(1, p - 2)
    print(f"Шаг 2: Виктор выбрал r = {r}")
    print(f"        Виктор отправляет r Пегги")
    
    # Шаг 3: Пегги вычисляет w = k - a*r mod (p-1)
    w = (k - a * r) % (p - 1)
    print(f"Шаг 3: Пегги вычислила w = k - a * r mod (p - 1) = {w}")
    print(f"        Пегги отправляет w Виктору")
    
    # Проверка Виктора: V == g^w * B^r mod p ?
    left = V
    right = (mod_pow(g, w, p) * mod_pow(B, r, p)) % p
    
    print(f"\nПРОВЕРКА ВИКТОРА:")
    print(f"  V = {left}")
    print(f"  g ^ w * B ^ r mod p = {right}")
    
    if left == right:
        print("  ✅ Проверка ПРОЙДЕНА! Пегги доказала знание a.")
    else:
        print("  ❌ Проверка НЕ ПРОЙДЕНА!")
    print()

