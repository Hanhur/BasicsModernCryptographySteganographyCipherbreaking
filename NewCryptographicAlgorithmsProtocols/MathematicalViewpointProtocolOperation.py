# Работа протокола с математической точки зрения
# -*- coding: utf-8 -*-
"""
Однораундовый протокол Zero-Knowledge Proof (ZKP)
на основе задачи дискретного логарифмирования.

Аналог: Протокол Шнорра (Schnorr protocol) в упрощённом виде.
Математика: r = c ^ x = (g ^ y) ^ x = g ^ (xy) = (g ^ x) ^ y = b ^ y = V (mod p)
"""

import random

# ------------------- 1. ИНИЦИАЛИЗАЦИЯ (Общие параметры) -------------------
# Это открытые параметры, известные и Пегги, и Виктору
p = 2741      # Простое число (модуль)
g = 7         # Генератор (примитивный корень по модулю p)

# ------------------- 2. ЭТАП ПЕГГИ (Доказывающая сторона) -------------------
print("=" * 50)
print("ЭТАП 1: Генерация утверждения (Setup)")
print("=" * 50)

# Секретное число Пегги (знание которого она хочет доказать)
x = 88
print(f"Секрет Пегги (x): {x}")

# Вычисляем публичное утверждение: b = g^x mod p
b = pow(g, x, p)  # pow(base, exp, mod) — встроенная функция для модульного возведения
print(f"Публичное утверждение (b = g ^ x mod p): {b}")
print(f"Проверка: 7 ^ {x} mod {p} = {b}\n")

# ------------------- 3. ЭТАП ВИКТОРА (Проверяющая сторона) -------------------
print("=" * 50)
print("ЭТАП 2: Вызов (Challenge)")
print("=" * 50)

# Виктор выбирает случайное число y (секрет Виктора)
y = 67  # В реальном протоколе это случайное число, здесь мы берём из примера
print(f"Случайное число Виктора (y): {y}")

# Вычисляем вызов: c = g^y mod p
c = pow(g, y, p)
print(f"Вызов Виктора (c = g ^ y mod p): {c}")
print(f"Проверка: 7 ^ {y} mod {p} = {c}\n")

# ------------------- 4. ОТВЕТ ПЕГГИ (Response) ----------------------------
print("=" * 50)
print("ЭТАП 3: Ответ Пегги")
print("=" * 50)

# Пегги, зная свой секрет x и получив c, вычисляет:
# r = c^x mod p
r = pow(c, x, p)
print(f"Пегги вычисляет: r = c ^ x mod p = {c} ^ {x} mod {p}")
print(f"Ответ Пегги (r): {r}\n")

# ------------------- 5. ПРОВЕРКА ВИКТОРА (Verification) --------------------
print("=" * 50)
print("ЭТАП 4: Проверка Виктора")
print("=" * 50)

# Виктор, зная публичное b и свой секрет y, вычисляет:
# V = b^y mod p
V = pow(b, y, p)
print(f"Виктор вычисляет: V = b ^ y mod p = {b} ^ {y} mod {p}")
print(f"Результат Виктора (V): {V}")

# Сравниваем
print("\n" + "=" * 50)
print("РЕЗУЛЬТАТ ПРОВЕРКИ")
print("=" * 50)

if r == V:
    print("✅ УСПЕХ! r == V")
    print(f"   {r} == {V}")
    print("\nМатематическое объяснение:")
    print(f"   r = c ^ x = (g ^ y) ^ x = g ^ {y * x} = g ^ {x * y} = (g ^ x) ^ y = b ^ y = V")
    print("   => Пегги доказала знание секрета x, не раскрыв его!")
else:
    print("❌ ОШИБКА! r != V")
    print(f"   {r} != {V}")

# ------------------- 6. ДОПОЛНИТЕЛЬНАЯ ДЕМОНСТРАЦИЯ (Связь с DH) ------------
print("\n" + "=" * 50)
print("СВЯЗЬ С ПРОТОКОЛОМ ДИФФИ — ХЕЛЛМАНА")
print("=" * 50)

print(f"Общий секрет (g ^ (x * y)) = g ^ {x * y} mod {p} = {pow(g, x * y, p)}")
print("\nСпособы вычисления этого общего секрета:")
print(f"1. Пегги:  c ^ x = {c} ^ {x} = {r}")
print(f"2. Виктор: b ^ y = {b} ^ {y} = {V}")
print("Оба способа дают одинаковый результат, т.к. это один и тот же общий секрет!")

# ------------------- 7. ПРОВЕРКА НА СЛУЧАЙНЫХ ЧИСЛАХ (Тест) ----------------
print("\n" + "=" * 50)
print("ТЕСТ: Случайный запуск протокола (для уверенности)")
print("=" * 50)

# Генерируем случайные x и y (секреты)
random_x = random.randint(2, p - 2)
random_y = random.randint(2, p - 2)

# Вычисления по тому же алгоритму
b_test = pow(g, random_x, p)
c_test = pow(g, random_y, p)
r_test = pow(c_test, random_x, p)
V_test = pow(b_test, random_y, p)

print(f"Случайный секрет Пегги: x = {random_x}")
print(f"Случайный секрет Виктора: y = {random_y}")
print(f"r = {r_test}")
print(f"V = {V_test}")
print(f"Результат: {'✅ Равны' if r_test == V_test else '❌ Не равны'}")