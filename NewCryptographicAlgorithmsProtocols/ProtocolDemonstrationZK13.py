# 5. ПРАВИЛЬНЫЙ ПРОТОКОЛ: Schnorr (интерактивный)
# ============================================

def schnorr_protocol(p, g, s, P):
    """
    Реализация протокола Шнорра (интерактивный вариант)
    Это исправленная версия ZK13, которая действительно работает!
    """
    print("\n" + "=" * 50)
    print("ПРОТОКОЛ ШНОРРА (правильная версия)")
    print("=" * 50)
    
    # Фаза 1: Боб генерирует эфимерный ключ
    k = random.randint(2, p - 2)
    r = pow(g, k, p)
    print(f"Боб: k = {k}, r = g ^ k mod p = {r}")
    
    # Фаза 2: Алиса отправляет вызов (challenge)
    c = random.randint(1, p - 2)
    print(f"Алиса -> Боб: вызов c = {c}")
    
    # Фаза 3: Боб вычисляет ответ
    # F = k + s*c mod (p-1)
    F = (k + s * c) % (p - 1)
    print(f"Боб: F = k + s * c = {F}")
    
    # Фаза 4: Боб отправляет ответ Алисе
    print(f"Боб -> Алиса: F = {F}")
    
    # Фаза 5: Алиса проверяет
    # Проверка: g^F ≡ r * P^c (mod p)
    left = pow(g, F, p)
    right = (r * pow(P, c, p)) % p
    
    print(f"\nАлиса проверяет:")
    print(f"left = g ^ F mod p = {left}")
    print(f"right = r * P ^ c mod p = {right}")
    print(f"left == right? {left == right}")
    
    if left == right:
        print("✅ Доказательство верно! Алиса убедилась, что Боб знает s.")
        print("   (Алиса не узнала s, только то, что Боб его знает)")
    else:
        print("❌ Доказательство неверно!")
    
    return left == right

