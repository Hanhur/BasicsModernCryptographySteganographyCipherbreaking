# 7. АТАКА НА ПОВТОРНОЕ ИСПОЛЬЗОВАНИЕ k
# ============================================

def demonstrate_reuse_attack(p, g, s):
    """
    Демонстрация уязвимости при повторном использовании k
    """
    print("\n" + "=" * 50)
    print("АТАКА НА ПОВТОРНОЕ ИСПОЛЬЗОВАНИЕ k")
    print("=" * 50)
    
    # Боб использует один и тот же k дважды
    k = random.randint(2, p - 2)
    print(f"Боб использует k = {k} дважды")
    
    # Сообщение 1
    m1 = "Hello"
    c1 = int(hashlib.sha256(f"{m1}".encode()).hexdigest(), 16) % (p - 1)
    F1 = (k + s * c1) % (p - 1)
    
    # Сообщение 2
    m2 = "World"
    c2 = int(hashlib.sha256(f"{m2}".encode()).hexdigest(), 16) % (p - 1)
    F2 = (k + s * c2) % (p - 1)
    
    print(f"Сообщение 1: c1 = {c1}, F1 = {F1}")
    print(f"Сообщение 2: c2 = {c2}, F2 = {F2}")
    
    # Атака: вычисляем s
    # F1 - F2 = s*(c1 - c2) mod (p-1)
    delta_F = (F1 - F2) % (p - 1)
    delta_c = (c1 - c2) % (p - 1)
    
    # Находим обратное к delta_c по модулю (p-1)
    # Используем расширенный алгоритм Евклида
    def egcd(a, b):
        if a == 0:
            return (b, 0, 1)
        else:
            g, y, x = egcd(b % a, a)
            return (g, x - (b // a) * y, y)
    
    g_c, inv, _ = egcd(delta_c, p - 1)
    
    if g_c == 1:
        s_recovered = (delta_F * inv) % (p - 1)
        print(f"Злоумышленник вычислил: s = {s_recovered}")
        print(f"Реальный s = {s}")
        print(f"s совпадает? {s_recovered == s}")
        if s_recovered == s:
            print("✅ АТАКА УСПЕШНА! Секрет раскрыт!")
        else:
            print("❌ Атака не удалась (маловероятно)")
    else:
        print(f"Невозможно вычислить s (gcd(delta_c, p - 1) = {g_c} != 1)")

