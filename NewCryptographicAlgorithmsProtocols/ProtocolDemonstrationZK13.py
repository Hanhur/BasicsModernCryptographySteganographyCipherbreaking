# 6. НЕИНТЕРАКТИВНЫЙ ВАРИАНТ (с хешем)
# ============================================

def noninteractive_zk(p, g, s, P, message = "Hello, Alice!"):
    """
    Неинтерактивный вариант: Боб отправляет доказательство без вызова от Алисы.
    Использует хеш-функцию для генерации вызова.
    """
    print("\n" + "=" * 50)
    print("НЕИНТЕРАКТИВНЫЙ ПРОТОКОЛ (с хешем)")
    print("=" * 50)
    
    # Фаза 1: Боб генерирует эфимерный ключ
    k = random.randint(2, p - 2)
    r = pow(g, k, p)
    print(f"Боб: k = {k}, r = {r}")
    
    # Фаза 2: Боб генерирует вызов из хеша
    # c = H(r || P || message)
    hash_input = f"{r}{P}{message}".encode()
    c = int(hashlib.sha256(hash_input).hexdigest(), 16) % (p - 1)
    print(f"Боб: c = H(r || P || message) = {c}")
    
    # Фаза 3: Боб вычисляет ответ
    F = (k + s * c) % (p - 1)
    print(f"Боб: F = {F}")
    
    # Фаза 4: Боб отправляет (r, F, message) Алисе
    print(f"Боб -> Алиса: (r = {r}, F = {F}, message='{message}')")
    
    # Фаза 5: Алиса проверяет
    # Алиса вычисляет c' = H(r || P || message)
    c_prime = int(hashlib.sha256(f"{r}{P}{message}".encode()).hexdigest(), 16) % (p - 1)
    print(f"Алиса: c' = H(r || P || message) = {c_prime}")
    
    # Проверка: g^F ≡ r * P^c' (mod p)
    left = pow(g, F, p)
    right = (r * pow(P, c_prime, p)) % p
    
    print(f"left = g ^ F mod p = {left}")
    print(f"right = r * P ^ c' mod p = {right}")
    print(f"left == right? {left == right}")
    
    if left == right:
        print("✅ Доказательство верно! Боб знает s.")
    else:
        print("❌ Доказательство неверно!")
    
    return left == right

