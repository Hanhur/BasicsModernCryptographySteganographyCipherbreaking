def generate_keys(p, g):
    """
    Боб генерирует:
    - s: секретный ключ (случайное число)
    - P: публичный ключ P = g ^ s mod p
    """
    # Секретный ключ s (1 < s < p-1)
    s = random.randint(2, p - 2)
    
    # Публичный ключ P = g^s mod p
    P = pow(g, s, p)
    
    print(f"Боб: секретный ключ s = {s}")
    print(f"Боб: публичный ключ P = {P}")
    
    return s, P

