def bob_prove(p, g, s, P):
    """
    Боб генерирует доказательство:
    1. Выбирает случайное k (эфимерный ключ)
    2. Вычисляет r = g^k mod p
    3. Вычисляет F = s * k mod (p-1)
    4. Отправляет (r, F) Алисе
    
    Возвращает: (r, F) - доказательство
    """
    # 1. Выбор случайного k (1 < k < p-1)
    k = random.randint(2, p - 2)
    print(f"Боб: выбрал случайное k = {k}")
    
    # 2. Вычисление r = g^k mod p
    r = pow(g, k, p)
    print(f"Боб: вычислил r = {r}")
    
    # 3. Вычисление F = s * k mod (p-1)
    F = (s * k) % (p - 1)
    print(f"Боб: вычислил F = {F}")
    
    # 4. Боб отправляет (r, F) Алисе
    print(f"Боб -> Алиса: (r = {r}, F = {F})")
    
    return r, F

